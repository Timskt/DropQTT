//! Broker passwords belong to the OS credential store, not to localStorage.
//!
//! Before this module the connect password was serialized into
//! `dropqtt_active_broker` and into every entry of `dropqtt_broker_profiles`, which
//! on Windows means plaintext JSON inside the WebView2 profile directory: anyone who
//! can read that folder can read the broker credentials. What is stored there now is a
//! random, meaningless reference; the secret itself goes to the platform store
//! (Credential Manager on Windows, Keychain on macOS, Secret Service on Linux).
//!
//! Three rules hold this together:
//!
//! - **The secret never comes back to JavaScript.** There is no "read" command: a
//!   reference is resolved inside the process that opens the socket, so the plaintext
//!   cannot be re-persisted by accident or printed by a debug statement in the UI.
//! - **A missing secret is an error, never an anonymous connect.** If a reference
//!   exists but the store cannot answer for it, connecting fails with a message that
//!   says what to do. Silently dropping the credential would produce a
//!   `bad username or password` from the broker, which reads like a network fault.
//! - **Error strings never carry the secret.** `keyring::Error::BadEncoding` renders
//!   the bytes it rejected, so every variant is mapped by hand; see `describe`.
//!
//! Every operation comes in two shapes: `*_with(store, …)`, which is given its store
//! and is what the tests exercise, and the plain name, which resolves the process
//! store and is what the commands and the connect path call.

use std::sync::{Arc, OnceLock, RwLock};

use serde::Serialize;

use crate::protocol::BrokerConfig;
use crate::webhook::WebhookConfig;

/// Namespace for every credential this app writes, so nothing here can collide with
/// another application's entries or overwrite one by accident.
pub const SERVICE: &str = "DropQTT";

/// Probed with a read of a key that is never written; "no entry" means the store
/// answered, which is all the availability check needs to know.
const AVAILABILITY_PROBE: &str = "availability-probe";

/// What the UI stores in `BrokerConfig.secretRef`: an opaque id, generated by the
/// caller. Constrained so a hand-edited localStorage value cannot name an arbitrary
/// credential in the shared store.
fn valid_reference(reference: &str) -> bool {
    !reference.is_empty()
        && reference.len() <= 64
        && reference
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// What a reference points at. Each kind is its own prefix inside the `DropQTT`
/// namespace, so a webhook header reference can never be used to read a broker
/// password, even when a hand-edited file names the same id under both.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SecretKind {
    Broker,
    WebhookHeader,
}

impl SecretKind {
    fn prefix(self) -> &'static str {
        match self {
            SecretKind::Broker => "broker",
            SecretKind::WebhookHeader => "webhook",
        }
    }

    /// The IPC spelling. Absent means broker, which is what every caller sent before
    /// webhook headers had a kind of their own.
    pub fn parse(raw: Option<&str>) -> Result<Self, String> {
        match raw {
            None | Some("broker") => Ok(SecretKind::Broker),
            Some("webhook") => Ok(SecretKind::WebhookHeader),
            Some(_) => Err("unknown credential kind".to_string()),
        }
    }
}

/// The account name inside the `DropQTT` namespace.
pub fn account_of(kind: SecretKind, reference: &str) -> Result<String, String> {
    if !valid_reference(reference) {
        return Err(
            "the credential reference is not a valid identifier; re-enter the value".to_string(),
        );
    }
    Ok(format!("{}:{reference}", kind.prefix()))
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct SecretStatus {
    /// False when the platform store could not be reached at all.
    pub available: bool,
    /// Whether this build was compiled against a real platform store. False means the
    /// dependency has no backend here, so nothing can be stored securely at all.
    pub supported: bool,
    /// Short, human-readable reason when either flag is false. Never contains a secret.
    pub reason: Option<String>,
}

/// A credential store. `Ok(None)` means "the store works and this reference has no
/// value"; `Err` means "the store could not answer", which callers must not confuse
/// with "no password".
pub trait CredentialStore: Send + Sync {
    fn get(&self, account: &str) -> Result<Option<String>, String>;
    fn set(&self, account: &str, value: &str) -> Result<(), String>;
    fn remove(&self, account: &str) -> Result<(), String>;
    /// False when this implementation cannot keep anything. Availability is a
    /// separate question from support.
    fn supported(&self) -> bool;
}

pub struct KeyringStore;

impl CredentialStore for KeyringStore {
    fn get(&self, account: &str) -> Result<Option<String>, String> {
        let entry = entry(account)?;
        match entry.get_password() {
            Ok(value) => Ok(Some(value)),
            Err(keyring::Error::NoEntry) => Ok(None),
            Err(error) => Err(describe(&error)),
        }
    }

    fn set(&self, account: &str, value: &str) -> Result<(), String> {
        let entry = entry(account)?;
        entry.set_password(value).map_err(|error| describe(&error))
    }

    fn remove(&self, account: &str) -> Result<(), String> {
        let entry = entry(account)?;
        match entry.delete_credential() {
            Ok(()) | Err(keyring::Error::NoEntry) => Ok(()),
            Err(error) => Err(describe(&error)),
        }
    }

    fn supported(&self) -> bool {
        // Cargo.toml gives each of these targets a real backend, and only those
        // targets. `keyring` itself would compile a silent in-process mock if a
        // feature set were ever dropped, so this mirrors that table rather than
        // trusting the crate to have picked one: an unsupported platform must report
        // unsupported, and the UI must then keep saying so instead of pretending.
        cfg!(any(
            target_os = "windows",
            target_os = "macos",
            target_os = "ios",
            target_os = "linux",
            target_os = "freebsd",
            target_os = "openbsd"
        ))
    }
}

fn entry(account: &str) -> Result<keyring::Entry, String> {
    keyring::Entry::new(SERVICE, account).map_err(|error| describe(&error))
}

/// `Error`'s own `Display` prints the rejected bytes for `BadEncoding` and passes the
/// backend's message through for the failure variants -- both are exactly what this
/// module exists to protect, and there is no way to know what a platform put in there.
/// So every variant is mapped to an authored string. Numeric limits are the only thing
/// quoted back, because those are counts rather than content.
fn describe(error: &keyring::Error) -> String {
    match error {
        keyring::Error::NoEntry => "no credential is stored under this reference".to_string(),
        keyring::Error::BadEncoding(_) => {
            "the stored credential is not valid UTF-8; overwrite it by re-entering the password"
                .to_string()
        }
        keyring::Error::TooLong(_, limit) => format!(
            "the credential is too long for the platform store (the limit here is {limit} characters)"
        ),
        keyring::Error::Invalid(_, _) => {
            "the platform store rejected this credential".to_string()
        }
        keyring::Error::Ambiguous(_) => {
            "several credentials share this reference in the platform store; re-enter the password"
                .to_string()
        }
        keyring::Error::PlatformFailure(_) => {
            "the system credential store failed; it may be locked or full".to_string()
        }
        keyring::Error::NoStorageAccess(_) => {
            "the system credential store could not be reached; it may need to be unlocked"
                .to_string()
        }
        // `Error` is `#[non_exhaustive]`, so a future variant must not become a leak.
        _ => "the system credential store rejected the request".to_string(),
    }
}

static STORE_OVERRIDE: RwLock<Option<Arc<dyn CredentialStore>>> = RwLock::new(None);
static DEFAULT_STORE: OnceLock<Arc<dyn CredentialStore>> = OnceLock::new();

pub fn store() -> Arc<dyn CredentialStore> {
    if let Ok(guard) = STORE_OVERRIDE.read() {
        if let Some(custom) = guard.as_ref() {
            return custom.clone();
        }
    }
    DEFAULT_STORE
        .get_or_init(|| Arc::new(KeyringStore) as Arc<dyn CredentialStore>)
        .clone()
}

pub fn resolve_with(backend: &dyn CredentialStore, config: &mut BrokerConfig) -> Result<(), String> {
    let Some(reference) = config.secret_ref.clone() else {
        return Ok(());
    };
    if config.password.as_deref().is_some_and(|p| !p.is_empty()) {
        // The draft the user just typed wins over the reference it is replacing.
        return Ok(());
    }
    let account = account_of(SecretKind::Broker, &reference)?;
    match backend.get(&account)? {
        Some(value) => {
            config.password = Some(value);
            Ok(())
        }
        None => Err(format!(
            "no password is stored for this broker (reference {reference}); re-enter it in Settings"
        )),
    }
}

/// Fill in `password` from the credential store when the config points at one.
pub fn resolve(config: &mut BrokerConfig) -> Result<(), String> {
    resolve_with(&*store(), config)
}

pub fn status_with(backend: &dyn CredentialStore) -> SecretStatus {
    if !backend.supported() {
        return SecretStatus {
            available: false,
            supported: false,
            reason: Some("this build has no platform credential store".to_string()),
        };
    }
    let account = format!("broker:{AVAILABILITY_PROBE}");
    match backend.get(&account) {
        Ok(_) => SecretStatus {
            available: true,
            supported: true,
            reason: None,
        },
        Err(reason) => SecretStatus {
            available: false,
            supported: true,
            reason: Some(reason),
        },
    }
}

pub fn status() -> SecretStatus {
    status_with(&*store())
}

/// Store a new secret. An empty value is rejected rather than written: a stored
/// empty string would later read as "no password" in `resolve_with`, which is the one
/// confusion this module must not create.
pub fn put_with(
    backend: &dyn CredentialStore,
    kind: SecretKind,
    reference: &str,
    value: &str,
) -> Result<(), String> {
    if value.is_empty() {
        return Err(
            "an empty value is not stored; clear the credential instead of blanking it".to_string(),
        );
    }
    backend.set(&account_of(kind, reference)?, value)
}

pub fn put(kind: SecretKind, reference: &str, value: &str) -> Result<(), String> {
    put_with(&*store(), kind, reference, value)
}

pub fn delete_with(backend: &dyn CredentialStore, kind: SecretKind, reference: &str) -> Result<(), String> {
    backend.remove(&account_of(kind, reference)?)
}

pub fn delete(kind: SecretKind, reference: &str) -> Result<(), String> {
    delete_with(&*store(), kind, reference)
}

/// Distinguishes "never stored" from "cannot be read", so the UI can say which.
pub fn exists_with(backend: &dyn CredentialStore, kind: SecretKind, reference: &str) -> Result<bool, String> {
    backend
        .get(&account_of(kind, reference)?)
        .map(|value| value.is_some())
}

pub fn exists(kind: SecretKind, reference: &str) -> Result<bool, String> {
    exists_with(&*store(), kind, reference)
}

/// The sink with every stored header value loaded into `headers`, and no references
/// left over. A stored value replaces a plain header of the same name rather than
/// being sent beside it, so the request carries one `Authorization`, not two.
///
/// The error names the header, never the value, and never a reason the platform
/// supplied -- `CredentialStore` errors are authored strings already.
pub fn resolve_webhook_with(
    backend: &dyn CredentialStore,
    config: &WebhookConfig,
) -> Result<WebhookConfig, String> {
    if config.secret_headers.is_empty() {
        return Ok(config.clone());
    }
    let mut loaded = Vec::with_capacity(config.secret_headers.len());
    for (name, reference) in &config.secret_headers {
        let account = account_of(SecretKind::WebhookHeader, reference)?;
        match backend.get(&account)? {
            Some(value) => loaded.push((name.trim().to_string(), value)),
            None => {
                return Err(format!(
                    "no value is stored for the webhook header '{}'; re-enter it in the rule",
                    name.trim()
                ))
            }
        }
    }
    let shadowed = |candidate: &str| {
        loaded
            .iter()
            .any(|(name, _)| name.eq_ignore_ascii_case(candidate.trim()))
    };
    let headers = config
        .headers
        .iter()
        .filter(|(name, _)| !shadowed(name))
        .cloned()
        .chain(loaded.iter().cloned())
        .collect();
    Ok(WebhookConfig {
        headers,
        secret_headers: Vec::new(),
        ..config.clone()
    })
}

pub fn resolve_webhook(config: &WebhookConfig) -> Result<WebhookConfig, String> {
    resolve_webhook_with(&*store(), config)
}

/// An in-memory store: the test double, and the shape any future non-platform
/// backend would take.
pub struct MemoryStore {
    entries: std::sync::Mutex<std::collections::HashMap<String, String>>,
}

impl MemoryStore {
    pub fn new() -> Self {
        Self {
            entries: std::sync::Mutex::new(std::collections::HashMap::new()),
        }
    }

    pub fn peek(&self, account: &str) -> Option<String> {
        self.entries.lock().unwrap().get(account).cloned()
    }
}

impl Default for MemoryStore {
    fn default() -> Self {
        Self::new()
    }
}

impl CredentialStore for MemoryStore {
    fn get(&self, account: &str) -> Result<Option<String>, String> {
        Ok(self.entries.lock().unwrap().get(account).cloned())
    }
    fn set(&self, account: &str, value: &str) -> Result<(), String> {
        self.entries
            .lock()
            .unwrap()
            .insert(account.to_string(), value.to_string());
        Ok(())
    }
    fn remove(&self, account: &str) -> Result<(), String> {
        self.entries.lock().unwrap().remove(account);
        Ok(())
    }
    fn supported(&self) -> bool {
        true
    }
}

